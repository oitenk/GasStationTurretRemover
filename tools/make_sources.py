"""Generate the mod's sector and streaming block JSON from the vanilla game sectors.

The two standing turrets outside the q104 gas station are copied, unchanged, out of
the always-on part of their vanilla sectors into a new sector whose only node range
is the "q104" variant of the station's devices prefab. The quest already switches
that variant on during Life During Wartime and off when it ends.

Phantom Liberty ships its own copies of both sectors and of the streaming block, with
the turrets at other indices but the same node counts, so the mod comes in two
editions: one built from the base game's files and one from Phantom Liberty's. The
script also writes the edition's .archive.xl, so its deletions always match the data.

Inputs are WolvenKit JSON exports (tools\\wkjson read, game version 2.5 or later) of
these three files, taken from basegame_3_nightcity.archive for the base-game edition
and from ep1\\ep1_1_nightcity.archive for the Phantom Liberty edition:
  base\\worlds\\03_night_city\\_compiled\\default\\exterior_-29_-67_1_0.streamingsector
  base\\worlds\\03_night_city\\_compiled\\default\\exterior_-29_-68_1_0.streamingsector
  base\\worlds\\03_night_city\\_compiled\\default\\blocks\\all.streamingblock

usage: python make_sources.py <base-game|phantom-liberty> <folder with the three .json exports> <repo root>
Writes source\\<edition>\\... and <edition>\\archive\\pc\\mod\\GasStationTurretRemover.archive.xl.
"""
import copy
import json
import os
import sys

DEFAULT = 'base\\worlds\\03_night_city\\_compiled\\default\\'
MOD_DIR = 'mod\\gas_station_turret_remover\\'
SECTOR_PATH = MOD_DIR + 'gas_station_turrets.streamingsector'
BLOCK_PATH = MOD_DIR + 'gas_station_turrets.streamingblock'

DEVICES_PREFAB = ('$/03_night_city/se5/loc_q104_gas_station_prefabHHXSKEQ/'
                  'loc_q104_gas_station_gameplay_prefabDBGQ7JI/#loc_q104_gas_station_devices')
VARIANT_NAME = 'q104'

# Per edition: (sector, nodeData index, description) for each turret. The indices become
# the nodeDeletions in the .xl file, and the counts its expectedNodes. Measured on game
# version 2.5; 2.31 had 842 and 251 in both editions.
EDITIONS = {
    'base-game': [
        ('exterior_-29_-67_1_0', 840, 'east of the pumps'),
        ('exterior_-29_-68_1_0', 252, 'south of the pumps'),
    ],
    'phantom-liberty': [
        ('exterior_-29_-67_1_0', 845, 'east of the pumps'),
        ('exterior_-29_-68_1_0', 251, 'south of the pumps'),
    ],
}
# Node debug name and node ref of the turret in each sector.
TURRET_NAMES = {
    'exterior_-29_-67_1_0': ('{q104_gas_station_turret}1', DEVICES_PREFAB + '/#q104_gas_station_turret1'),
    'exterior_-29_-68_1_0': ('{q104_gas_station_turret}3', DEVICES_PREFAB + '/#q104_gas_station_turret3'),
}
EXPECTED_NODES = {'exterior_-29_-67_1_0': 3624, 'exterior_-29_-68_1_0': 1418}

XL_HEADER = '''# Gas Station Turret Remover ({edition} edition)
#
# The two standing turrets outside the Badlands gas station from Life During Wartime
# are taken out of the always-on part of their sectors and put back, unchanged, in a
# sector of this mod that belongs to the quest's own "q104" variant of the station's
# devices. The quest switches that variant on while it runs and off when it ends, so
# the turrets are only there during the quest.
#
# Generated by tools\\make_sources.py from {source}.
streaming:
  blocks:
    - mod\\gas_station_turret_remover\\gas_station_turrets.streamingblock
  sectors:
'''
XL_SECTOR = '''    - path: base\\worlds\\03_night_city\\_compiled\\default\\{sector}.streamingsector
      expectedNodes: {count}
      nodeDeletions:
        # q104_gas_station_turret{number}, {where}
        - index: {index}
          type: worldEntityNode
'''
EDITION_TITLES = {'base-game': 'base game', 'phantom-liberty': 'Phantom Liberty'}
EDITION_SOURCES = {'base-game': "the base game's files", 'phantom-liberty': "Phantom Liberty's copies of the files"}


def load(folder, name):
    with open(os.path.join(folder, name + '.json'), encoding='utf-8') as f:
        return json.load(f)


def renumber(node, counters):
    """Give every handle and buffer in a copied node a fresh id.

    References between handles inside the node follow the new ids; a reference to a
    handle outside the node cannot be carried over and stops the build.
    """
    mapping = {}

    def assign(obj):
        if isinstance(obj, dict):
            if 'HandleId' in obj:
                mapping[obj['HandleId']] = str(counters['handle'])
                obj['HandleId'] = mapping[obj['HandleId']]
                counters['handle'] += 1
            if 'BufferId' in obj:
                obj['BufferId'] = str(counters['buffer'])
                counters['buffer'] += 1
            for v in obj.values():
                assign(v)
        elif isinstance(obj, list):
            for v in obj:
                assign(v)

    def relink(obj):
        if isinstance(obj, dict):
            if 'HandleRefId' in obj:
                if obj['HandleRefId'] not in mapping:
                    raise SystemExit('copied node references a handle outside itself')
                obj['HandleRefId'] = mapping[obj['HandleRefId']]
            for v in obj.values():
                relink(v)
        elif isinstance(obj, list):
            for v in obj:
                relink(v)

    assign(node)
    relink(node)


def main(edition, src, repo):
    if edition not in EDITIONS:
        raise SystemExit(f'unknown edition {edition}; use one of {", ".join(EDITIONS)}')
    out = os.path.join(repo, 'source', edition)
    block = load(src, 'all.streamingblock')
    descriptors = {d['data']['DepotPath']['$value']: d for d in block['Data']['RootChunk']['descriptors']}

    template = None
    nodes, node_data, node_refs = [], [], []
    box_min = [float('inf')] * 3
    box_max = [float('-inf')] * 3
    counters = {'handle': 0, 'buffer': 1}  # buffer 0 is the nodeData buffer

    xl = XL_HEADER.format(edition=EDITION_TITLES[edition], source=EDITION_SOURCES[edition])
    for sector_name, index, where in EDITIONS[edition]:
        debug_name, ref = TURRET_NAMES[sector_name]
        xl += XL_SECTOR.format(sector=sector_name, count=EXPECTED_NODES[sector_name],
                               number=ref[-1], where=where, index=index)
        sector = load(src, sector_name + '.streamingsector')
        root = sector['Data']['RootChunk']
        entries = root['nodeData']['Data']
        if len(entries) != EXPECTED_NODES[sector_name]:
            raise SystemExit(f'{sector_name} has {len(entries)} nodes, expected {EXPECTED_NODES[sector_name]}')
        if index >= root['variantIndices'][1]:
            raise SystemExit(f'{sector_name}[{index}] is not in the always-on range')
        if entries[index] != root['persistentNodes'][index]:
            raise SystemExit(f'{sector_name}[{index}] differs between nodeData and persistentNodes')

        entry = copy.deepcopy(entries[index])
        node = copy.deepcopy(root['nodes'][int(entry['nodeIdx'])])
        if node['Data']['$type'] != 'worldEntityNode':
            raise SystemExit(f'{sector_name}[{index}] is a {node["Data"]["$type"]}, expected worldEntityNode')
        if node['Data']['debugName']['$value'] != debug_name:
            raise SystemExit(f'{sector_name}[{index}] is {node["Data"]["debugName"]["$value"]}, expected {debug_name}')
        ref_entry = next((r for r in root['nodeRefs'] if r['$value'] == ref), None)
        if ref_entry is None:
            raise SystemExit(f'{sector_name} does not list {ref}')
        renumber(node, counters)

        entry['nodeIdx'] = str(len(nodes))
        nodes.append(node)
        node_data.append(entry)
        node_refs.append(copy.deepcopy(ref_entry))

        # Stream the new sector whenever either source sector would be streamed.
        sbox = descriptors[DEFAULT + sector_name + '.streamingsector']['streamingBox']
        for i, axis in enumerate('XYZ'):
            box_min[i] = min(box_min[i], sbox['Min'][axis])
            box_max[i] = max(box_max[i], sbox['Max'][axis])

        if template is None:
            template = sector
            vanilla_desc = descriptors[DEFAULT + sector_name + '.streamingsector']

    variant = next(v for v in vanilla_desc['variants']
                   if v['nodeRef']['$value'] == DEVICES_PREFAB and v['name']['$value'] == VARIANT_NAME)

    # Sector: one empty always-on range, then the q104 variant range holding both turrets.
    sector = {
        'Header': {k: v for k, v in template['Header'].items() if k not in ('ExportedDateTime', 'ArchiveFileName')},
        'Data': {
            'Version': template['Data']['Version'],
            'BuildVersion': template['Data']['BuildVersion'],
            'RootChunk': None,
            'EmbeddedFiles': [],
        },
    }
    troot = template['Data']['RootChunk']
    root = {
        '$type': 'worldStreamingSector',
        'category': troot['category'],
        'cookingPlatform': troot['cookingPlatform'],
        'externInplaceResource': troot['externInplaceResource'],
        'level': troot['level'],
        'localInplaceResource': [],
        'nodeData': {k: v for k, v in troot['nodeData'].items() if k != 'Data'},
        'nodeRefs': node_refs,
        'nodes': nodes,
        'persistentNodeIndex': 0,
        # Since 2.5 a sector also lists its node entries per range: the always-on range
        # in persistentNodes, each variant range in variantNodes.
        'persistentNodes': [],
        'variantIndices': [0, 0],
        'variantNodes': [copy.deepcopy(node_data)],
        'version': troot['version'],
    }
    root['nodeData']['BufferId'] = '0'
    root['nodeData']['Data'] = node_data
    sector['Data']['RootChunk'] = root

    # Block: one descriptor for the new sector, with the vanilla q104 variant copied as range 1.
    new_variant = copy.deepcopy(variant)
    new_variant['rangeIndex'] = 1
    block_index = {'$type': 'worldStreamingBlockIndex', 'oup': 'Base', 'rldGridCell': 0}
    descriptor = {
        '$type': 'worldStreamingSectorDescriptor',
        'blockIndex': copy.deepcopy(block_index),
        'category': vanilla_desc['category'],
        'data': {'DepotPath': {'$type': 'ResourcePath', '$storage': 'string', '$value': SECTOR_PATH},
                 'Flags': 'Soft'},
        'level': vanilla_desc['level'],
        'numNodeRanges': 2,
        'questPrefabNodeRef': {'$type': 'NodeRef', '$storage': 'uint64', '$value': '0'},
        'streamingBox': {
            '$type': 'Box',
            'Max': {'$type': 'Vector4', 'W': 1, 'X': box_max[0], 'Y': box_max[1], 'Z': box_max[2]},
            'Min': {'$type': 'Vector4', 'W': 1, 'X': box_min[0], 'Y': box_min[1], 'Z': box_min[2]},
        },
        'variants': [new_variant],
    }
    new_block = {
        'Header': {k: v for k, v in block['Header'].items() if k not in ('ExportedDateTime', 'ArchiveFileName')},
        'Data': {
            'Version': block['Data']['Version'],
            'BuildVersion': block['Data']['BuildVersion'],
            'RootChunk': {
                '$type': 'worldStreamingBlock',
                'cookingPlatform': block['Data']['RootChunk']['cookingPlatform'],
                'descriptors': [descriptor],
                'index': block_index,
            },
            'EmbeddedFiles': [],
        },
    }

    for path, data in ((SECTOR_PATH, sector), (BLOCK_PATH, new_block)):
        dest = os.path.join(out, *path.split('\\')) + '.json'
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(data, f, indent=2)
            f.write('\n')
        print('wrote', dest)

    xl_path = os.path.join(repo, edition, 'archive', 'pc', 'mod', 'GasStationTurretRemover.archive.xl')
    os.makedirs(os.path.dirname(xl_path), exist_ok=True)
    with open(xl_path, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(xl)
    print('wrote', xl_path)


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
